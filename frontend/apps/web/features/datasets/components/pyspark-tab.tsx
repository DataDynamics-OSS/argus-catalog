export function generateFullLoadScript(dataset: DatasetDetail): string {
  const t = transferTarget(dataset)
  const jdbc = jdbcInfo(t.type)
  const s3Base = `s3a://${DATALAKE_BUCKET}/${t.s3Prefix}`
  const columnList = sourceColumns(dataset).map((c) => `            ${c}`).join(",\n")

  return `#!/usr/bin/env python3
"""${dataset.name} → S3 데이터레이크 전체 적재 (스냅숏).

용도:
  - 초기 1회 백필(이후 일단위 증분으로 전환)
  - 수정시각 컬럼이 없어 증분 추출이 불가능한 테이블의 일단위 스냅숏

대상: ${s3Base}/snapshot_dt=<적재일>/  (Parquet, Snappy)
      일단위 증분(${t.partition}=…)과 다른 경로다 — 증분용 Hive 외부 테이블에는 잡히지 않는다.

실행 예:
    spark-submit --jars ${jdbc.jar} full_load_${t.slug}.py

Generated by Argus Catalog.
"""

import argparse
import os
from datetime import date

from pyspark.sql import SparkSession

SOURCE_TABLE = "${t.sourceTable.replace(/"/g, '\\"')}"
S3_BASE = "${s3Base}"

JDBC_URL = "${jdbc.url}"
JDBC_DRIVER = "${jdbc.driver}"
JDBC_USER = os.environ["${t.secretPrefix}_USERNAME"]
JDBC_PASSWORD = os.environ["${t.secretPrefix}_PASSWORD"]


def main() -> None:
    parser = argparse.ArgumentParser(description="${dataset.name} 전체 적재")
    parser.add_argument("--snapshot-date", default=date.today().isoformat(),
                        help="스냅숏 일자 (YYYY-MM-DD, 기본: 오늘)")
    args = parser.parse_args()
    snapshot_date = args.snapshot_date

    spark = (
        SparkSession.builder
        .appName("full-load-${t.datasourceId}-${t.slug}")
        # S3A 설정은 증분 적재 스크립트의 build_spark() 주석 참고
        .getOrCreate()
    )

    # 부분 쿼리 별칭에 AS 를 쓰지 않는다(Oracle 호환)
    query = f"""(
        SELECT
${columnList}
        FROM {SOURCE_TABLE}
    ) src"""

    reader = (
        spark.read.format("jdbc")
        .option("url", JDBC_URL)
        .option("driver", JDBC_DRIVER)
        .option("dbtable", query)
        .option("user", JDBC_USER)
        .option("password", JDBC_PASSWORD)
        .option("fetchsize", "10000")
    )
${parallelReadHint(dataset, 16)}

    df = reader.load()
    target_path = f"{S3_BASE}/snapshot_dt={snapshot_date}"
    df.write.mode("overwrite").parquet(target_path)
    # 행 수는 쓴 파일에서 센다 — df.count() 는 원본을 한 번 더 읽는다.
    print(f"[full-load] {SOURCE_TABLE}: {spark.read.parquet(target_path).count():,} rows → {target_path}")

    spark.stop()


if __name__ == "__main__":
    main()
`
}

