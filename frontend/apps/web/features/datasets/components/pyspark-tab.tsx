/** 병렬 읽기 안내(숫자형 PK 가 있으면 partitionColumn 예시). */
function parallelReadHint(dataset: DatasetDetail, partitions: number): string {
  const pk = numericPrimaryKey(dataset)
  if (!pk) {
    return `    # 이 테이블은 숫자형 PK 가 없어 단일 커넥션으로 읽는다.
    # 대용량이면 숫자형 컬럼을 partitionColumn 으로 지정해 병렬화를 검토한다.`
  }
  return `    # 대용량 테이블 병렬 읽기 — PK(${pk.field_path}) 범위를 나눠 동시 추출.
    # lowerBound/upperBound 는 사전 조회(min/max)로 채우거나 운영값으로 고정한다.
    # reader = (
    #     reader.option("partitionColumn", "${pk.field_path}")
    #     .option("numPartitions", "${partitions}")
    #     .option("lowerBound", "1")
    #     .option("upperBound", "<MAX_${pk.field_path.toUpperCase()}>")
    # )`
}

export function generateIncrementalScript(dataset: DatasetDetail): string {
  const t = transferTarget(dataset)
  const jdbc = jdbcInfo(t.type)
  const s3Base = `s3a://${DATALAKE_BUCKET}/${t.s3Prefix}`
  const candidates = incrementalCandidates(dataset)
  const chosen = candidates[0]?.name ?? "<INCREMENTAL_COLUMN>"
  const columnList = sourceColumns(dataset).map((c) => `            ${c}`).join(",\n")
  const incExpr = sourceIdent(t.type, chosen)

  return `#!/usr/bin/env python3
"""${dataset.name} → S3 데이터레이크 일단위 증분 적재.

원본:   ${dataset.datasource.name} (${t.type}) — JDBC 표준 접속
대상:   ${s3Base}/${t.partition}=<적재일>/  (Parquet, Snappy)
주기:   일 1회 (전일 데이터 적재). 같은 날짜 재실행 시 해당 파티션만 덮어써 멱등.

실행 예:
    spark-submit --jars ${jdbc.jar} ingest_${t.slug}.py                  # 전일분
    spark-submit --jars ${jdbc.jar} ingest_${t.slug}.py --target-date 2026-06-01

적재한 파티션은 Airflow · Kestra 탭의 Hive 하위 탭 코드로 Hive 외부 테이블에 등록한다.

Generated by Argus Catalog.
"""

import argparse
import os
from datetime import date, datetime, timedelta

from pyspark.sql import SparkSession

# ── 적재 대상 ────────────────────────────────────────────────────────────────
SOURCE_TABLE = "${t.sourceTable.replace(/"/g, '\\"')}"
S3_BASE = "${s3Base}"
PARTITION = "${t.partition}"

JDBC_URL = "${jdbc.url}"
JDBC_DRIVER = "${jdbc.driver}"
# 자격 증명은 코드에 넣지 말고 환경변수/시크릿 매니저로 주입한다.
JDBC_USER = os.environ["${t.secretPrefix}_USERNAME"]
JDBC_PASSWORD = os.environ["${t.secretPrefix}_PASSWORD"]

${candidateCommentBlock(candidates, chosen)}
INCREMENTAL_COLUMN = "${incExpr.replace(/"/g, '\\"')}"


def build_spark() -> SparkSession:
    spark = (
        SparkSession.builder
        .appName("ingest-${t.datasourceId}-${t.slug}")
        # S3A 접속 설정 — 환경에 맞게 선택:
        #  - AWS EMR/EKS(IRSA): 별도 설정 불필요 (IAM Role 사용 권장)
        #  - 사내 MinIO/Ceph 등 S3 호환 스토리지:
        # .config("spark.hadoop.fs.s3a.endpoint", "http://<S3_ENDPOINT>:9000")
        # .config("spark.hadoop.fs.s3a.access.key", os.environ["S3_ACCESS_KEY"])
        # .config("spark.hadoop.fs.s3a.secret.key", os.environ["S3_SECRET_KEY"])
        # .config("spark.hadoop.fs.s3a.path.style.access", "true")
        .getOrCreate()
    )
    return spark


def main() -> None:
    parser = argparse.ArgumentParser(description="${dataset.name} 일단위 증분 적재")
    parser.add_argument(
        "--target-date",
        default=(date.today() - timedelta(days=1)).isoformat(),
        help="적재 대상 일자 (YYYY-MM-DD, 기본: 어제)",
    )
    args = parser.parse_args()
    target_date = args.target_date
    next_date = (datetime.strptime(target_date, "%Y-%m-%d").date() + timedelta(days=1)).isoformat()

    spark = build_spark()

    # 일단위 필터 — DATE(컬럼) = '...' 같은 함수 비교 대신 반개구간 비교를 쓴다.
    # (컬럼을 함수로 감싸면 원본 DB 인덱스를 타지 못한다)
    # 부분 쿼리의 별칭에는 AS 를 쓰지 않는다 — Oracle 은 테이블 별칭의 AS 를 받지 않는다.
    pushdown_query = f"""(
        SELECT
${columnList}
        FROM {SOURCE_TABLE}
        WHERE {INCREMENTAL_COLUMN} >= ${sourceDayStart(t.type, "{target_date}")}
          AND {INCREMENTAL_COLUMN} <  ${sourceDayStart(t.type, "{next_date}")}
    ) src"""

    reader = (
        spark.read.format("jdbc")
        .option("url", JDBC_URL)
        .option("driver", JDBC_DRIVER)
        .option("dbtable", pushdown_query)
        .option("user", JDBC_USER)
        .option("password", JDBC_PASSWORD)
        .option("fetchsize", "10000")
    )
${parallelReadHint(dataset, 8)}

    df = reader.load()

    # 일자 디렉터리({PARTITION}=YYYY-MM-DD)에 직접 쓴다 — 파티션 값은 경로가 갖는다.
    # 데이터에 같은 이름의 컬럼을 넣으면 Spark · Hive 가 디렉터리를 읽을 때 컬럼이 겹쳐 실패한다.
    # mode=overwrite + 단일 파티션 경로 직접 지정 → 같은 날짜 재실행에 멱등.
    target_path = f"{S3_BASE}/{PARTITION}={target_date}"
    (
        df.repartition(1)  # 일 배치 데이터가 크면 제거하거나 적정 파티션 수로 조정
        .write.mode("overwrite")
        .parquet(target_path)
    )
    # 행 수는 쓴 파일에서 센다 — df.count() 는 원본을 한 번 더 읽는다.
    row_count = spark.read.parquet(target_path).count()
    print(f"[ingest] {SOURCE_TABLE} {target_date}: {row_count:,} rows → {target_path}")

    spark.stop()


if __name__ == "__main__":
    main()
`
}

